"""French attribute vocabulary -> `project.attribute` subject keys (6.3).

The subject key is what makes `supersedes` decidable ("same slot"), so this
table is the engine's working vocabulary, not the generator's. Keeping it here
(decoupled from `gen.ledger.ATTRIBUTES`) is what lets the engine resolve a
subject for a *real* corpus that was never generated by a ledger.

Resolution today: (a) rules over this lexicon — the shipped path — and nothing
automatic beyond it. 6.3's proposals (b) cosine lookup, (c) LLM, (d/e) span
head, (f) drawer classifier, (g) graph projection were each built, wired and
measured against one pre-registered gate (D-026…D-036); none crossed the bar
on real French speech, so the code was removed (D-037) — its verdicts live in
`runs/` and REPORT §6e. The one remaining non-rules supplier is `gold`
(`gold_subject.py`): hand-labelled annotation for the real-data demos, which
SUPPLIES keys and extracts nothing. `normalize_attr` stays here because the
labelling tool validates every drawer name through it — gold labels and (any
future) model output share one format rule.
"""

from __future__ import annotations

import re
from typing import Any

# canonical attribute key -> French surface forms (lowercase, accent-insensitive)
ATTRIBUTE_LEXICON: dict[str, list[str]] = {
    "launch_date": ["date de lancement", "lancement", "date du lancement",
                    "mise sur le marché", "go-live", "golive", "sortie"],
    "budget": ["budget", "enveloppe", "ligne budgétaire", "crédits", "financement",
               "montant alloué", "coût", "coûts"],
    "vendor": ["prestataire", "fournisseur", "vendor", "partenaire", "agence retenue",
               "sous-traitant"],
    "scope": ["périmètre", "scope", "champ fonctionnel", "lots", "phase pilote"],
    "deadline_report": ["deadline du rapport", "rapport", "compte rendu", "livrable",
                        "rendu"],
    "stack": ["stack", "stack technique", "techno", "socle technique", "outils"],
    "pricing": ["tarif", "prix", "grille tarifaire", "pricing", "facturation"],
    "hiring": ["recrutement", "embauche", "poste", "candidat", "recruter"],
    "risk_compliance": ["risque de conformité", "conformité", "rgpd", "audit",
                        "mise en conformité"],
    "env_strategy": ["stratégie d'environnements", "environnements", "recette",
                     "integration", "staging"],
    "owner.budget": ["pilotage de budget", "responsable budget", "qui tient le budget"],
    "delay": ["retard", "glissement", "reporté", "décalage"],
    "status": ["statut", "avancement", "état d'avancement"],
}

# ordered longest-first so "date de lancement" beats "lancement"
_FORMS: list[tuple[str, str]] = sorted(
    [(form, key) for key, forms in ATTRIBUTE_LEXICON.items() for form in forms],
    key=lambda x: -len(x[0]))

# stop-words that must never be mistaken for an attribute surface form
GENERIC_TERMS = {
    "le", "la", "les", "des", "du", "de", "un", "une", "est", "sont", "on", "nous",
    "ce", "c", "ça", "au", "aux", "et", "ou", "à", "a", "pour", "par", "avec",
    "sans", "que", "qui", "dans", "sur", "plus", "moins",
}


def fold(text: str) -> str:
    import unicodedata

    t = unicodedata.normalize("NFD", text.lower())
    return "".join(c for c in t if not unicodedata.combining(c))


def match_attribute(text: str) -> str | None:
    """Rule (a): longest surface form found in the unit wins."""
    hay = fold(text)
    for form, key in _FORMS:
        if fold(form) in hay:
            return key
    return None


def subject_key(project: str | None, attribute: str | None,
                owner_slot: bool = False) -> str | None:
    if not attribute:
        return None
    if owner_slot:
        return f"{(project or 'global').lower()}.owner.{attribute}"
    return f"{(project or 'global').lower()}.{attribute}"


def as_owner_key(subject: str) -> str:
    """`atlas.budget` -> `atlas.owner.budget` (idempotent)."""
    if not subject or ".owner." in subject:
        return subject
    project, _, attr = subject.partition(".")
    if not attr:
        return subject
    return f"{project}.owner.{attr}"


def resolve(text: str, project: str | None, *, owner_slot: bool = False
            ) -> str | None:
    attr = match_attribute(text)
    return subject_key(project, attr, owner_slot)


def attributes_for(project: str | None) -> list[str]:
    return sorted({k.split(".", 1)[-1] for k in ATTRIBUTE_LEXICON})


def same_slot(a: str | None, b: str | None) -> bool:
    return bool(a) and a == b


# ------------------------------------------------------------- key validation
# Moved here from the removed LLM extractor (D-037): the labelling tool
# (`tools/summre_label.py`) runs every hand-written drawer through exactly
# this function, so gold labels could never drift from the format a model
# answer was validated against. The rule survives its first customer.
_COIN_TOK = re.compile(r"[a-z0-9]+")

_FORMS_BY_LEN = sorted(
    ((fold(form), key) for key, forms in ATTRIBUTE_LEXICON.items() for form in forms),
    key=lambda x: -len(x[0]))


def normalize_attr(raw: Any) -> str | None:
    """Validate one proposed drawer name — or None (refuse).

    Three outcomes, in order: exact vocabulary hit (including surface forms);
    a well-shaped coined key; refusal. A coined key must look like a key:
    lowercase, accents folded, at most three tokens, no stop-words, ≤ 40
    chars. A refusal is a real answer — a free sentence filed as a slot key
    would merge every thread it ever repeated, so the labeller's "buffet"
    passes and "prochaine reunion on en reparlera" does not."""
    if raw is None or isinstance(raw, bool):
        return None
    s = fold(str(raw)).strip()
    if s in ("", "null", "none", "n/a", "na"):
        return None
    if s in ATTRIBUTE_LEXICON:
        return s
    for forms, key in _FORMS_BY_LEN:
        if forms == s:
            return key
    toks = [t for t in _COIN_TOK.findall(s.replace("-", " ").replace("_", " "))
            if t not in GENERIC_TERMS]
    if not toks or len(toks) > 3:
        return None
    coined = "_".join(toks)
    return coined if len(coined) <= 40 else None


def echoes_project(attr: str, project: str | None) -> bool:
    """True when a coined key is made only of the project's own tokens.

    Measured failure (D-028 smoke): a model answered the PROJECT NAME as the
    subject; filed under that key, every unit of the meeting shares one slot
    and all threads merge — the false-merge the gate bounds. The labelling
    tool refuses such names the same way."""
    if not project:
        return False
    ptoks = set(_COIN_TOK.findall(fold(str(project))))
    atoks = set(_COIN_TOK.findall(attr))
    return bool(atoks) and atoks <= ptoks
